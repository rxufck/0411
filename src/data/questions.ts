const sign = (id: string, value?: string | number): Illustration => ({ kind: 'sign', sign: { id, value } });
const signs = (...ids: string[]): Illustration => ({ kind: 'signs', signs: ids.map((id) => ({ id })) });

let counter = 0;
function q(
  topic: TopicId,
  text: string,
  options: string[],
  explanation: string,
  rule?: string,
  image?: Illustration,
): Question {
  counter += 1;
  // Правильный ответ всегда пишем первым — при показе варианты перемешиваются.
  return { id: `${topic}-${counter}`, topic, text, options, correct: 0, explanation, rule, image };
}

